// TestSceneIdentityIndexMatchesSceneIDAgainstSegmentID pins the durable
// SpecScene shape used by the Kaufmann payload: the scene carries the script
// segment id in Scene.ID (`cold-case`) while the VidRush result carries it in
// SegmentID and a numeric SceneID. The entity catalog lookup must find the
// scene instead of treating the query as persona-non-grata.
func TestSceneIdentityIndexMatchesSceneIDAgainstSegmentID(t *testing.T) {
	spec := scriptpkg.SpecSceneOutput{Scenes: []scriptpkg.SpecScene{
		{ID: "cold-case", Index: 0},
		{ID: "discovery", Index: 1},
	}}
	idx := buildSceneIdentityIndex(spec)
	segment := scriptpkg.VidRushSegmentResult{SegmentID: "discovery", SceneID: "scene-1", Position: 1}
	if got := idx.sceneFor(segment); got != 1 {
		t.Fatalf("sceneFor = %d, want 1 (Scene.ID must match SegmentID)", got)
	}
}

func TestSceneIdentityIndexFallsBackToOrdinal(t *testing.T) {
	spec := scriptpkg.SpecSceneOutput{Scenes: []scriptpkg.SpecScene{
		{ID: "cold-case", Index: 0},
		{ID: "discovery", Index: 1},
	}}
	idx := buildSceneIdentityIndex(spec)
	// Both ids were regenerated by an intermediate producer; only the ordinal
	// still identifies the scene.
	segment := scriptpkg.VidRushSegmentResult{SegmentID: "regenerated-a", SceneID: "regenerated-b", Position: 1}
	if got := idx.sceneFor(segment); got != 1 {
		t.Fatalf("sceneFor = %d, want the ordinal fallback to scene 1", got)
	}
}

// TestPersonCatalogIdentityForQueryFallsBackToSegmentInsights covers the stage
// order: annotations are not projected yet, but the PERSON is already in
// segment.Insights and must still produce a canonical catalog identity.
func TestPersonCatalogIdentityForQueryFallsBackToSegmentInsights(t *testing.T) {
	spec := scriptpkg.SpecSceneOutput{Scenes: []scriptpkg.SpecScene{{ID: "cold-case", Index: 0}}}
	segment := scriptpkg.VidRushSegmentResult{
		SegmentID: "cold-case", SceneID: "scene-0", Position: 0,
		Insights: scriptpkg.SegmentInsights{Entities: []scriptpkg.ExtractedEntity{
			{Value: "Anastasia Trofimova", Type: "PERSON"},
		}},
	}
	identity, ok, err := personCatalogIdentityForQuery(spec, buildSceneIdentityIndex(spec), segment, "Anastasia Trofimova")
	if err != nil {
		t.Fatalf("identity fallback: %v", err)
	}
	if !ok || identity.CanonicalEntityID != "person:anastasia-trofimova" {
		t.Fatalf("identity = %+v, ok=%v, want person:anastasia-trofimova", identity, ok)
	}
}
