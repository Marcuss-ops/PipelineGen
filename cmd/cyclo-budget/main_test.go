const knownComplexitySource = `package sample

func Known(x int) int {
	if x > 0 && x < 10 {
		return 1
	}
	for i := 0; i < x; i++ {
		if i%2 == 0 {
			continue
		}
	}
	switch x {
	case 1:
		return 1
	case 2:
		return 2
	}
	return 0
}
`

func TestComplexityCountsDecisionFamily(t *testing.T) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "known.go", knownComplexitySource, 0)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	var body *ast.BlockStmt
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok {
			body = fn.Body
		}
	}
	if body == nil {
		t.Fatal("function body not found")
	}
	// 1 + if + && + for + if + two switch cases.
	if got, want := complexity(body), 7; got != want {
		t.Fatalf("complexity = %d, want %d", got, want)
	}
}

func TestScanAndRatchet(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "internal", "sample")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	source := `package sample

func Alpha(x int) int {
	if x > 0 {
		return 1
	}
	return 0
}

func Beta(x int) int {
	if x > 0 {
		return 1
	}
	for i := 0; i < x; i++ {
		_ = i
	}
	return 0
}
`
	if err := os.WriteFile(filepath.Join(dir, "sample.go"), []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}

	current, err := scan(root, 1)
	if err != nil {
		t.Fatalf("scan: %v", err)
	}
	if len(current) != 2 {
		t.Fatalf("scan found %d functions, want 2: %+v", len(current), current)
	}
	alphaKey := "internal/sample.Alpha"
	betaKey := "internal/sample.Beta"
	if current[alphaKey].Complexity != 2 || current[betaKey].Complexity != 3 {
		t.Fatalf("unexpected complexities: %+v", current)
	}

	base := baseline{Version: baselineVersion, Threshold: 1, Functions: map[string]int{alphaKey: 2, betaKey: 3}}
	if result := checkFindings(current, base, 1); len(result.Failures) != 0 || len(result.Warnings) != 0 {
		t.Fatalf("matching baseline should pass: %+v", result)
	}

	delete(base.Functions, betaKey)
	result := checkFindings(current, base, 1)
	if len(result.Failures) != 1 || !contains(result.Failures, "new function above budget") {
		t.Fatalf("new offender should fail: %+v", result)
	}

	base.Functions[betaKey] = 3
	base.Functions[alphaKey] = 1
	result = checkFindings(current, base, 1)
	if len(result.Failures) != 1 || !contains(result.Failures, "complexity grew") {
		t.Fatalf("growth should fail: %+v", result)
	}

	base.Functions[alphaKey] = 3
	result = checkFindings(current, base, 1)
	if len(result.Failures) != 0 || len(result.Warnings) != 1 || !contains(result.Warnings, "improved") {
		t.Fatalf("improvement should warn, not fail: %+v", result)
	}
}

func TestBaselineRoundTrip(t *testing.T) {
	path := filepath.Join(t.TempDir(), "architecture", "cyclo_budget.json")
	want := baseline{Version: baselineVersion, Threshold: 40, Functions: map[string]int{"internal/sample.Alpha": 42}}
	if err := writeBaseline(path, want); err != nil {
		t.Fatalf("write: %v", err)
	}
	got, err := loadBaseline(path)
	if err != nil {
		t.Fatalf("load: %v", err)
	}
	if got.Version != want.Version || got.Threshold != want.Threshold || got.Functions["internal/sample.Alpha"] != 42 {
		t.Fatalf("round-trip mismatch: %+v", got)
	}
}

func TestScanSkipsTestsAndGenerated(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "internal", "sample")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	files := map[string]string{
		"prod.go":      "package sample\nfunc Prod(x int) int { if x > 0 { return 1 }; return 0 }\n",
		"prod_test.go": "package sample\nfunc TestProd(x int) int { if x > 0 { return 1 }; return 0 }\n",
		"generated.go": "// Code generated by test. DO NOT EDIT.\npackage sample\nfunc Generated(x int) int { if x > 0 { return 1 }; return 0 }\n",
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	current, err := scan(root, 1)
	if err != nil {
		t.Fatalf("scan: %v", err)
	}
	if len(current) != 1 {
		t.Fatalf("scan should keep only production code, got %+v", current)
	}
	if _, ok := current["internal/sample.Prod"]; !ok {
		t.Fatalf("Prod missing from scan: %+v", current)
	}
}

func contains(values []string, substring string) bool {
	for _, value := range values {
		if strings.Contains(value, substring) {
			return true
		}
	}
	return false
}
